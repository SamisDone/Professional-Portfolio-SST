"""
Writes the animated banner for the GitHub profile README (the SamisDone
repository), in the site's own type and colours.

    python scripts/make-profile-banner.py path/to/SamisDone/assets/hello.svg

A case file, the site's mascot, drops in beside a speech bubble, waves, and
the bubble types "Hi, I'm Samonwita." a letter at a time. The file then
blinks now and again and waves every few seconds; everything else holds
still. The folder tab is the orange of the site's file tabs, the body is
paper with ink rules for lines of text, and the bubble carries the same hard
ink shadow as everything pressable on the site.

Text is outlined from src/fonts, because GitHub shows an SVG as an image with
no access to web fonts. The animation is CSS inside the SVG, which GitHub
plays; no script runs there. Under reduced motion the finished frame shows.
"""
import re
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
css = (ROOT / "src/index.css").read_text(encoding="utf8")
content = (ROOT / "src/data/content.ts").read_text(encoding="utf8")


def token(name):
    return re.search(rf"--{name}:\s*(#[0-9a-fA-F]{{6}})", css).group(1)


def field(name):
    return re.search(rf'{name}:\s*"([^"]+)"', content).group(1)


PAPER, PAPER2, INK, INK2 = token("paper"), token("paper-2"), token("ink"), token("ink-2")
ORANGE, PROOF = token("orange"), token("proof")
FIRST = field("name").split()[0]
HELLO = f"Hi, I'm {FIRST}."
LABEL = f'{field("standfirst")} / {field("openTo")}'.upper()
LEAD = re.search(r'positioning:\s*"([^"]+)"', content).group(1)

heading = instantiateVariableFont(TTFont(ROOT / "src/fonts/Archivo.woff2"), {"wght": 800, "wdth": 112})
body = instantiateVariableFont(TTFont(ROOT / "src/fonts/Archivo.woff2"), {"wght": 400, "wdth": 100})
mono = TTFont(ROOT / "src/fonts/MartianMono-Label.woff2")


def glyph_runs(font, text, size, x, y, tracking=0.0):
    """Each character's outline as its own path, for typing, and the advance."""
    glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
    scale = size / font["head"].unitsPerEm
    cursor, runs = x, []
    for i, ch in enumerate(text):
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyphs)
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, cursor, y)))
        runs.append((ch, pen.getCommands()))
        cursor += glyphs[name].width * scale + (tracking * size if i < len(text) - 1 else 0)
    return runs, cursor - x


def outline(font, text, size, x, y, tracking=0.0):
    runs, width = glyph_runs(font, text, size, x, y, tracking)
    return "".join(d for _, d in runs), width


def wrap(font, text, size, width):
    """Greedy lines of at most `width`, measured with the font itself."""
    lines, line = [], ""
    for word in text.split():
        trial = f"{line} {word}".strip()
        if line and outline(font, trial, size, 0, 0)[1] > width:
            lines.append(line)
            line = word
        else:
            line = trial
    return lines + [line]


W, H = 1280, 390

# ---- The bubble and its words, sized to the greeting.
TX, TY, TSIZE = 404, 132, 68
letters, hello_w = glyph_runs(heading, HELLO, TSIZE, TX, TY, -0.01)
BX, BY = 372, 58
BW, BH = hello_w + 64, 104
TYPE_AT, TYPE_STEP = 900, 55  # ms: when the first letter lands, then each next

label_d, _ = outline(mono, LABEL, 15, BX, 216, 0.06)
# The lead inside the rule's width, its lines balanced, so the last is never
# one word on its own: the narrowest measure that still takes as few lines.
MEASURE = W - 60 - BX
fewest = len(wrap(body, LEAD, 25, MEASURE))
measure = next(m for m in range(MEASURE // 2, MEASURE + 1, 8) if len(wrap(body, LEAD, 25, m)) == fewest)
lead_d = "".join(outline(body, line, 25, BX, 258 + i * 34)[0] for i, line in enumerate(wrap(body, LEAD, 25, measure)))
RULE_Y = 330

typed = "\n".join(
    f'    <path class="ch" style="animation-delay:{TYPE_AT + i * TYPE_STEP}ms" d="{d}"/>'
    for i, (ch, d) in enumerate(letters)
    if d
)
TYPED_BY = TYPE_AT + len(letters) * TYPE_STEP

svg = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" aria-labelledby="t">
  <title id="t">{HELLO} A paper case file with an orange tab waves hello. {LABEL.title()}. {LEAD}</title>
  <!-- Generated by scripts/make-profile-banner.py in the portfolio repository. Edit that, not this. -->
  <style>
    .fall {{ animation: fall 420ms cubic-bezier(0.2, 0, 0, 1) both; }}
    .arm {{ transform-origin: 262px 196px; animation: hello 1500ms ease-in-out 420ms both, wave 1100ms ease-in-out 6s infinite; }}
    .eye {{ transform-box: fill-box; transform-origin: center; animation: blink 4.2s steps(1) 2.4s infinite; }}
    .bubble {{ transform-origin: {BX}px {BY + BH}px; animation: stamp 160ms cubic-bezier(0.2, 0, 0, 1) 700ms both; }}
    .ch {{ opacity: 0; animation: type 1ms linear forwards; }}
    .meta {{ animation: show 240ms linear {TYPED_BY + 100}ms both; }}
    .rule {{ transform-origin: {BX}px {RULE_Y}px; animation: draw 480ms linear {TYPED_BY}ms both; }}
    @keyframes fall {{ from {{ transform: translateY(-36px); opacity: 0; }} }}
    @keyframes hello {{
      0%, 100% {{ transform: rotate(0deg); }}
      20%, 60% {{ transform: rotate(-22deg); }}
      40%, 80% {{ transform: rotate(12deg); }}
    }}
    @keyframes wave {{
      0%, 100% {{ transform: rotate(0deg); }}
      30% {{ transform: rotate(-22deg); }}
      60% {{ transform: rotate(12deg); }}
    }}
    @keyframes blink {{ 0% {{ transform: scaleY(1); }} 96% {{ transform: scaleY(0.12); }} }}
    @keyframes stamp {{ from {{ transform: scale(1.06); opacity: 0; }} }}
    @keyframes type {{ to {{ opacity: 1; }} }}
    @keyframes show {{ from {{ opacity: 0; }} }}
    @keyframes draw {{ from {{ transform: scaleX(0); }} }}
    @media (prefers-reduced-motion: reduce) {{
      .fall, .arm, .eye, .bubble, .ch, .meta, .rule {{ animation: none; opacity: 1; }}
    }}
  </style>
  <rect width="{W}" height="{H}" fill="{PAPER}"/>

  <!-- The case file. -->
  <g class="fall" stroke="{INK}" stroke-width="4" stroke-linejoin="miter">
    <!-- Legs and feet, behind the body. -->
    <path d="M120 300V336M188 300V336" fill="none" stroke-width="6"/>
    <path d="M104 336H128M180 336H204" fill="none" stroke-width="6"/>
    <!-- The still arm. -->
    <path d="M70 196L44 252" fill="none" stroke-width="6" stroke-linecap="square"/>
    <!-- The hard shadow, then the tab and body. -->
    <path d="M82 70H230L270 110V308H82Z" fill="{INK}" transform="translate(8 8)"/>
    <path d="M80 46H150L162 70H80Z" fill="{ORANGE}"/>
    <path d="M70 70H226L266 110V304H70Z" fill="{PAPER2}"/>
    <path d="M226 70V110H266" fill="{PAPER}"/>
    <!-- Face: two eyes that blink, and a smile. -->
    <rect class="eye" x="122" y="128" width="13" height="22" fill="{INK}" stroke="none"/>
    <rect class="eye" x="180" y="128" width="13" height="22" fill="{INK}" stroke="none"/>
    <path d="M136 176Q158 194 180 176" fill="none" stroke-width="5" stroke-linecap="round"/>
    <!-- Lines of text, one under a proof mark. -->
    <path d="M96 226H236M96 248H210M96 270H224" fill="none" stroke-width="3"/>
    <rect x="92" y="240" width="122" height="16" fill="{PROOF}" stroke-width="2"/>
    <path d="M100 248H206" fill="none" stroke-width="3"/>
    <!-- The waving arm, pivoting at the shoulder. -->
    <g class="arm">
      <path d="M262 196L306 140" fill="none" stroke-width="6" stroke-linecap="square"/>
      <!-- An open palm: square, like every corner on the site, with a thumb. -->
      <rect x="296" y="108" width="26" height="30" fill="{PAPER}"/>
      <path d="M296 128H286" fill="none" stroke-width="4"/>
    </g>
  </g>

  <!-- The bubble, its tail pointing at the file. -->
  <g class="bubble">
    <path d="M{BX + 8} {BY + 8}H{BX + BW + 8}V{BY + BH + 8}H{BX + 8}Z" fill="{INK}"/>
    <path d="M{BX} {BY}H{BX + BW}V{BY + BH}H{BX}V{BY + 66}L{BX - 30} {BY + 52}L{BX} {BY + 38}Z" fill="{PAPER}" stroke="{INK}" stroke-width="4" stroke-linejoin="miter"/>
  </g>
  <g fill="{INK}">
{typed}
  </g>

  <g class="meta">
    <path d="{label_d}" fill="{INK2}"/>
    <path d="{lead_d}" fill="{INK}"/>
  </g>
  <rect class="rule" x="{BX}" y="{RULE_Y}" width="{W - 60 - BX}" height="4" fill="{INK}"/>
</svg>
"""

out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "hello.svg"
out.write_text(svg, encoding="utf8")
print(f"{out}  {len(svg) // 1024}kB  bubble {BW:.0f}px  typed by {TYPED_BY}ms")
