"""
Writes docs/banner.svg, the animated banner at the top of the README.

    python scripts/make-banner.py

The text is outlined from the site's own fonts (src/fonts), so GitHub, which
shows an SVG as an image with no access to web fonts, draws it exactly. The
copy and colours are read from src/data/content.ts and src/index.css.

The banner plays the site's page-load motion once, in 600ms, and then holds
still (SMIL with fill="freeze"; nothing repeats): the label stamps, the 4px
rule draws left to right, the orange band wipes in behind the name, and the
lead stamps last. With reduced motion a CSS media query swaps in the finished
frame instead. Only opacity, transform and the drawn width move.
"""
import re
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
css = (ROOT / "src/index.css").read_text(encoding="utf8")
content = (ROOT / "src/data/content.ts").read_text(encoding="utf8")


def token(name):
    return re.search(rf"--{name}:\s*(#[0-9a-fA-F]{{6}})", css).group(1)


def field(name):
    return re.search(rf'{name}:\s*"([^"]+)"', content).group(1)


PAPER, INK, INK2, ORANGE = token("paper"), token("ink"), token("ink-2"), token("orange")
NAME = field("name").upper()  # t-display is uppercase
LABEL = f'{field("standfirst")} / {field("openTo")}'.upper()
LEAD = re.search(r'positioning:\s*"([^"]+)"', content).group(1)

archivo = TTFont(ROOT / "src/fonts/Archivo.woff2")
display = instantiateVariableFont(TTFont(ROOT / "src/fonts/Archivo.woff2"), {"wght": 850, "wdth": 125})
body = instantiateVariableFont(archivo, {"wght": 400, "wdth": 100})
mono = TTFont(ROOT / "src/fonts/MartianMono-Label.woff2")


def outline(font, text, size, x, y, tracking=0.0):
    """The text as one SVG path, its left edge at x and baseline at y. Returns
    the path data and the advance width. `tracking` is in em, as in the CSS."""
    glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
    scale = size / font["head"].unitsPerEm
    pen = SVGPathPen(glyphs)
    cursor = x
    for i, ch in enumerate(text):
        name = cmap[ord(ch)]
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, cursor, y)))
        cursor += glyphs[name].width * scale + (tracking * size if i < len(text) - 1 else 0)
    return pen.getCommands(), cursor - x


W, H, PAD = 1280, 340, 48

label_d, label_w = outline(mono, LABEL, 18, PAD, 70, tracking=0.06)

# The name as large as fits the band inside the frame, at most 84px.
_, w84 = outline(display, NAME, 84, 0, 0, tracking=-0.03)
size = min(84, 84 * (W - 2 * PAD - 40) / w84)
band_h = round(size * 1.05)
band_y = 100
name_d, name_w = outline(display, NAME, size, PAD + 18, band_y + band_h * 0.8, tracking=-0.03)
band_w = round(name_w + 36)

lead_y = band_y + band_h + 54
lead_d, lead_w = outline(body, LEAD, 26, PAD, lead_y)
rule_y = H - 56
rule_w = W - 2 * PAD

EASE = 'calcMode="spline" keyTimes="0;1" keySplines="0.2 0 0 1"'


def stamp(begin, cx, cy, use):
    """A stamp: from scale 1.06 and transparent to its place, in 120ms."""
    return f"""<g opacity="0"><animate attributeName="opacity" from="0" to="1" begin="{begin}s" dur="0.12s" fill="freeze" {EASE}/>
      <g transform="translate({cx:.1f} {cy:.1f})"><g><animateTransform attributeName="transform" type="scale" from="1.06" to="1" begin="{begin}s" dur="0.12s" fill="freeze" {EASE}/>
        <g transform="translate({-cx:.1f} {-cy:.1f})">{use}</g></g></g></g>"""


svg = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" aria-labelledby="t">
  <title id="t">{field("name")}. {field("standfirst")} / {field("openTo")}. {LEAD}</title>
  <!-- Generated by scripts/make-banner.py. Edit that, not this. -->
  <style>
    .still {{ display: none; }}
    @media (prefers-reduced-motion: reduce) {{
      .play {{ display: none; }}
      .still {{ display: inline; }}
    }}
  </style>
  <defs>
    <path id="label" d="{label_d}"/>
    <path id="name" d="{name_d}"/>
    <path id="lead" d="{lead_d}"/>
  </defs>
  <rect x="1" y="1" width="{W - 2}" height="{H - 2}" fill="{PAPER}" stroke="{INK}" stroke-width="2"/>

  <g class="play">
    {stamp(0, PAD + label_w / 2, 64, f'<use href="#label" fill="{INK}"/>')}
    <rect x="{PAD}" y="{band_y}" width="0" height="{band_h}" fill="{ORANGE}"><animate attributeName="width" from="0" to="{band_w}" begin="0.16s" dur="0.32s" fill="freeze" {EASE}/></rect>
    <rect x="{PAD}" y="{band_y}" width="{band_w}" height="{band_h}" fill="none" stroke="{INK}" stroke-width="2"/>
    <use href="#name" fill="{INK}"/>
    {stamp(0.48, PAD + lead_w / 2, lead_y - 9, f'<use href="#lead" fill="{INK2}"/>')}
    <rect x="{PAD}" y="{rule_y}" width="0" height="4" fill="{INK}"><animate attributeName="width" from="0" to="{rule_w}" begin="0s" dur="0.48s" fill="freeze" {EASE}/></rect>
  </g>

  <g class="still">
    <use href="#label" fill="{INK}"/>
    <rect x="{PAD}" y="{band_y}" width="{band_w}" height="{band_h}" fill="{ORANGE}" stroke="{INK}" stroke-width="2"/>
    <use href="#name" fill="{INK}"/>
    <use href="#lead" fill="{INK2}"/>
    <rect x="{PAD}" y="{rule_y}" width="{rule_w}" height="4" fill="{INK}"/>
  </g>
</svg>
"""
svg = re.sub(r"(\d+\.\d{2})\d+", r"\1", svg)  # two decimals is plenty at this size
out = ROOT / "docs/banner.svg"
out.write_text(svg, encoding="utf8", newline="\n")
print(f"{out.relative_to(ROOT)}: {len(svg.encode()) / 1024:.1f} kB, name at {size:.1f}px")
